def _preload_info() -> str:
    return f"l2_glob={CFG.l2_glob} | merged_exists={os.path.exists(CFG.l2_merged_csv)} | ts_is_ms={CFG.ts_is_ms}"

def _ensure_l2_cache() -> pd.DataFrame:
    """Load all L2 shards (or merged csv) once, add ts_sec, sort."""
    global _L2_CACHE
    if _L2_CACHE is not None:
        return _L2_CACHE
    # Prefer merged CSV if present — single read, often already sorted
    if CFG.l2_merged_csv and os.path.exists(CFG.l2_merged_csv):
        print(f"  [cache] loading merged {CFG.l2_merged_csv} ...")
        df = pd.read_csv(CFG.l2_merged_csv)
        # csv stores ts as int ms; ensure numeric
        df[CFG.c_ts] = df[CFG.c_ts].astype(np.int64)
    else:
        paths = glob.glob(CFG.l2_glob)
        if not paths:
            raise FileNotFoundError(f"No L2 files matched: {CFG.l2_glob}")
        print(f"  [cache] loading {len(paths)} parquet shards ...")
        frames = []
        for p in paths:
            try:
                frames.append(pd.read_parquet(p))
            except Exception as e:
                warnings.warn(f"skip {p}: {e}")
        df = pd.concat(frames, ignore_index=True)
    # Normalise
    if CFG.ts_is_ms:
        df["_ts_sec"] = df[CFG.c_ts].astype(np.float64) / 1000.0
    else:
        df["_ts_sec"] = df[CFG.c_ts].astype(np.float64)
    df = df.sort_values("_ts_sec").reset_index(drop=True)
    # Light type coercion for speed
    _L2_CACHE = df
    print(f"  [cache] loaded {len(df):,} rows  ts_sec {df['_ts_sec'].min():.0f} -> {df['_ts_sec'].max():.0f}  syms {df[CFG.c_sym].nunique()}")
    return df

