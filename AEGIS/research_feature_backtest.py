# SECTION 5 — STATISTICAL EVALUATION (OOS, no lookahead)
# ══════════════════════════════════════════════════════════════════
def auc_mannwhitney(y, score) -> float:
    y = np.asarray(y); score = np.asarray(score)
    # Drop NaNs in score
    mask = np.isfinite(score)
    y = y[mask]; score = score[mask]
    pos = score[y == 1]; neg = score[y == 0]
    if len(pos) == 0 or len(neg) == 0:
        return 0.5
    order = np.argsort(score); ranks = np.empty(len(score), dtype=np.float64); ranks[order] = np.arange(1, len(score)+1)
    U = float(ranks[y == 1].sum() - len(pos)*(len(pos)+1)/2.0)
    return float(U / (len(pos)*len(neg)))

def ks_stat(y, score) -> float:
    y = np.asarray(y); score = np.asarray(score)
    mask = np.isfinite(score)
    y = y[mask]; score = score[mask]
    a = np.sort(score[y == 1]); b = np.sort(score[y == 0])
    if len(a) == 0 or len(b) == 0:
        return 0.0
    grid = np.sort(np.unique(np.concatenate([a, b])))
    # Searchsorted for CDFs
    cdf_a = np.searchsorted(a, grid, side="right") / max(len(a), 1)
    cdf_b = np.searchsorted(b, grid, side="right") / max(len(b), 1)
    return float(np.max(np.abs(cdf_a - cdf_b)))

def evaluate(df: pd.DataFrame, feat_cols: List[str]) -> pd.DataFrame:
    df = df.sort_values("ts").reset_index(drop=True)
    # Drop rows where all feats are NaN?
    split = int(len(df) * 0.7)
    if split < 10 or len(df) - split < 10:
        print("  [eval] too few rows for 70/30 split")
        split = len(df) // 2
    train, test = df.iloc[:split], df.iloc[split:]
    print(f"  [eval] train {len(train)}  test {len(test)}  base_rate train {train['y'].mean():.3f}  test {test['y'].mean():.3f}")
    rec = []
    for c in feat_cols:
        auc_tr = auc_mannwhitney(train["y"], train[c])
        auc_te = auc_mannwhitney(test["y"],  test[c])
        ks_te  = ks_stat(test["y"], test[c])
        rec.append({"feature": c, "auc_train": auc_tr, "auc_oos": auc_te, "ks_oos": ks_te,
                    "mean_pos_te": float(test.loc[test["y"]==1, c].mean()) if (test["y"]==1).any() else float("nan"),
                    "mean_neg_te": float(test.loc[test["y"]==0, c].mean()) if (test["y"]==0).any() else float("nan")})
    rep = pd.DataFrame(rec).sort_values("auc_oos", ascending=False)
    return rep

def combined_logistic(df: pd.DataFrame, feat_cols: List[str]) -> None:
    """Does the feature set add edge JOINTLY? (needs scikit-learn)"""
    try:
        from sklearn.linear_model import LogisticRegression
        from sklearn.metrics import roc_auc_score
        from sklearn.preprocessing import StandardScaler
    except ImportError:
        print("  scikit-learn not installed — skipping combined model"); return
    use_cols = [c for c in feat_cols if c != "hawkes_n"]
    sub = df.dropna(subset=use_cols)
    if len(sub) < 40:
        print("  combined: too few complete rows")
        return
    sub = sub.sort_values("ts").reset_index(drop=True)
    split = int(len(sub) * 0.7)
    Xtr, ytr = sub.iloc[:split][use_cols].fillna(0), sub.iloc[:split]["y"]
    Xte, yte = sub.iloc[split:][use_cols].fillna(0), sub.iloc[split:]["y"]
    # Standardize on train
    scaler = StandardScaler()
    Xtr_s = scaler.fit_transform(Xtr)
    Xte_s = scaler.transform(Xte)
    m = LogisticRegression(max_iter=2000, class_weight="balanced", solver="lbfgs")
    m.fit(Xtr_s, ytr)
    try:
        auc_tr = roc_auc_score(ytr, m.predict_proba(Xtr_s)[:,1])
        auc_te = roc_auc_score(yte, m.predict_proba(Xte_s)[:,1])
    except Exception:
        auc_tr = auc_te = float("nan")
    print(f"\n  Combined logistic ({len(use_cols)} feats)  AUC train={auc_tr:.3f}  AUC OOS={auc_te:.3f}")
    # Coef table
    coefs = sorted(zip(use_cols, m.coef_[0]), key=lambda x: abs(x[1]), reverse=True)
    print("    coefs |z|:", ", ".join(f"{k}={v:+.3f}" for k,v in coefs[:6]))

