def _read_range(sym: Optional[str], t0_sec: float, t1_sec: float) -> pd.DataFrame:
    """Slice the preloaded cache to [t0, t1] and optionally sym."""
    df = _ensure_l2_cache()
    # Use boolean mask on _ts_sec — fast enough for 1.3M rows; per-event ~0.3ms
    mask = (df["_ts_sec"] >= t0_sec) & (df["_ts_sec"] <= t1_sec)
    if sym is not None:
        mask &= (df[CFG.c_sym] == sym)
    return df.loc[mask].copy()

def load_l2(sym: str, t0: float, t1: float) -> pd.DataFrame:
    """Compatibility wrapper keeping original pseudocode signature (seconds)."""
    return _read_range(sym, t0, t1)

def load_futures(t0: float, t1: float) -> pd.DataFrame:
    if not CFG.futures_glob:
        return pd.DataFrame()
    # Futures parquet schema mirrors L2 (ts ms, lp). Reuse cache slicing if futures are in same archive:
    # Otherwise glob-load separately.
    paths = glob.glob(CFG.futures_glob)
    if not paths:
        return pd.DataFrame()
    frames = []
    for p in paths:
        try:
            df = pd.read_parquet(p)
            # normalise ts
            if CFG.ts_is_ms:
                df["_ts_sec"] = df[CFG.c_ts].astype(float) / 1000.0
            else:
                df["_ts_sec"] = df[CFG.c_ts].astype(float)
            df = df[(df["_ts_sec"] >= t0) & (df["_ts_sec"] <= t1)]
            if len(df):
                # For futures we treat index spot (kind==0) as proxy if no dedicated future sym
                frames.append(df)
        except Exception as e:
            warnings.warn(f"futures skip {p}: {e}")
    if not frames:
        return pd.DataFrame()
    out = pd.concat(frames, ignore_index=True).sort_values("_ts_sec")
    # Map to expected columns for feat_futures_lead_lag
    # Use sym==NIFTY (spot) as futures proxy if no futures sym
    if CFG.f_px in out.columns:
        out = out.rename(columns={CFG.f_px: "px", "_ts_sec": "ts"})
    elif "lp" in out.columns:
        out = out.rename(columns={"lp": "px", "_ts_sec": "ts"})
    else:
        return pd.DataFrame()
    # Keep only ts+px
    cols = [c for c in ["ts", "px"] if c in out.columns]
    return out[cols]

def _auto_extract_spikes() -> pd.DataFrame:
    """
    Auto-extract >=auto_target_pct spikes from raw L2 when spike_csv not provided.
    Mirrors AEGIS/core/causal_microstructure_pipeline.py logic:
      target window (t0, t0+45s], hit if any future price >=10% without >3% interim drawdown.
    Deduplicates same sym within 5 min. Returns cols [ts(sym seconds), sym, dir].
    Restricted to market hours 03:45-10:00 UTC (09:15-15:30 IST) and requires
    at least 3 ticks in the 2s pre-window to avoid illiquid artefacts.
    """
    df = _ensure_l2_cache()
    opts = df[df["kind"] == 2].copy() if "kind" in df.columns else df[df[CFG.c_sym] != "NIFTY"].copy()
    # Market-hours filter: 09:15-15:30 IST = 03:45-10:00 UTC
    # Derive hour in IST via UTC+5:30
    # Use _ts_sec (UTC) -> IST = UTC + 19800s
    ist_hour = ((opts["_ts_sec"].astype(np.float64) + 19800) % 86400) / 3600.0
    opts = opts[(ist_hour >= 9.25) & (ist_hour <= 15.5)]
    if CFG.auto_sample_days:
        opts["_day"] = pd.to_datetime(opts["_ts_sec"], unit="s").dt.strftime("%Y-%m-%d")
        opts = opts[opts["_day"].isin(CFG.auto_sample_days)]
    # Speed: sample decision times every 1s (not every tick) — matches live 1s evaluation cadence
    # This cuts loops 20-50x vs per-tick while still capturing all >=10% bursts (45s horizon)
    step_sec = 1.0
    print(f"  [spike-auto] scanning {len(opts):,} option ticks for >={CFG.auto_target_pct:.0f}% in {CFG.auto_target_window_sec:.0f}s (step {step_sec:.0f}s) ...")
    spikes: List[Dict] = []
    for sym, g in opts.groupby(CFG.c_sym, sort=False):
        g = g.sort_values("_ts_sec")
        ts = g["_ts_sec"].to_numpy(dtype=np.float64)
        lp = g[CFG.c_ltp].to_numpy(dtype=np.float64)
        if len(ts) < 10:
            continue
        t_min = float(ts[0] + CFG.pre_window_sec)
        t_max = float(ts[-1] - CFG.auto_target_window_sec)
        if t_max <= t_min:
            continue
        # Candidate t0s every step_sec
        t0_cands = np.arange(t_min, t_max, step_sec)
        last_hit_sec = -1e18
        for t0_sec in t0_cands:
            if t0_sec - last_hit_sec < CFG.auto_min_gap_ms / 1000.0:
                continue
            # Map t0_sec to nearest tick at or before t0
            idx0 = int(np.searchsorted(ts, t0_sec, side="right") - 1)
            if idx0 < 0 or idx0 >= len(lp):
                continue
            p0 = float(lp[idx0])
            if p0 < CFG.auto_min_price:
                continue
            t0_actual = float(ts[idx0])
            # Future window strictly after t0_actual
            j1 = int(np.searchsorted(ts, t0_actual + 0.001, side="left"))
            j2 = int(np.searchsorted(ts, t0_actual + CFG.auto_target_window_sec, side="right"))
            if j2 <= j1:
                continue
            future = lp[j1:j2]
            gains = (future - p0) / max(p0, 0.05) * 100.0
            cummax = np.maximum.accumulate(future)
            dds = (cummax - future) / max(p0, 0.05) * 100.0
            hit_idx = np.where(gains >= CFG.auto_target_pct)[0]
            if len(hit_idx) == 0:
                continue
            hi = int(hit_idx[0])
            if np.any(dds[:hi+1] > CFG.auto_max_drawdown_pct):
                continue
            j_pre0 = int(np.searchsorted(ts, t0_actual - CFG.pre_window_sec, side="left"))
            j_pre1 = int(np.searchsorted(ts, t0_actual, side="right"))
            if (j_pre1 - j_pre0) < 3:
                continue
            spikes.append({"ts": float(t0_actual), "sym": str(sym), "dir": "UP", "p_t0": p0, "gain": float(gains[hi])})
            last_hit_sec = t0_actual
    spikes_df = pd.DataFrame(spikes).sort_values("ts").reset_index(drop=True) if spikes else pd.DataFrame(columns=["ts","sym","dir"])
    # Compact to required cols
    if not spikes_df.empty:
        spikes_df = spikes_df[["ts","sym","dir"]]
    print(f"  [spike-auto] found {len(spikes_df)} events (deduped {CFG.auto_min_gap_ms/1000:.0f}s) — sample:")
    if len(spikes_df):
        print(spikes_df.head(5).to_string(index=False))
        print(spikes_df["sym"].value_counts().head(6).to_string())
    return spikes_df

def load_spikes() -> pd.DataFrame:
    if CFG.spike_csv and os.path.exists(CFG.spike_csv):
        df = pd.read_csv(CFG.spike_csv)
        # Handle ts_is_ms
        if CFG.ts_is_ms:
            # If ts column looks like ms (>=1e12), convert
            sample = df[CFG.s_ts].iloc[0] if len(df) else 0
            if sample > 1e11:
                df["_ts_sec"] = df[CFG.s_ts].astype(float) / 1000.0
            else:
                df["_ts_sec"] = df[CFG.s_ts].astype(float)
        else:
            df["_ts_sec"] = df[CFG.s_ts].astype(float)
        # Normalise dir
        def _norm_dir(v):
            s = str(v).strip().upper()
            if s in ("1","CALL","CE","C"): return "UP"
            if s in ("2","PUT","PE","P"): return "DOWN"
            if s in ("UP","DOWN"): return s
            return "UP"
        dir_col = df[CFG.s_dir].apply(_norm_dir) if CFG.s_dir in df.columns else "UP"
        out = pd.DataFrame({"ts": df["_ts_sec"].values, "sym": df[CFG.s_sym].astype(str).values, "dir": dir_col})
        return out.sort_values("ts").reset_index(drop=True)
    else:
        # Auto-extract from raw L2
        print(f"  [spike] no spike_csv at '{CFG.spike_csv}' — auto-extracting from L2 archive")
        return _auto_extract_spikes()


