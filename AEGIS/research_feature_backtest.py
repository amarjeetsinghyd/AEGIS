# SECTION 3a — FEATURE A: FUTURES LEAD-LAG
# ══════════════════════════════════════════════════════════════════
def feat_futures_lead_lag(fut: pd.DataFrame, event_ts: float, direction: str) -> Dict[str, float]:
    """
    Direction-adjusted futures returns over several lookbacks ending at the
    option event start. Positive => futures already moving WITH the spike.
    If no futures data, returns zeros and the feature will be flat (AUC 0.5).
    """
    out: Dict[str, float] = {}
    sign = 1.0 if direction == "UP" else -1.0
    if fut.empty or len(fut) < 3:
        return {f"futret_{lb}ms": 0.0 for lb in CFG.fut_lookbacks_ms}
    ts = fut["ts"].to_numpy(dtype=np.float64); px = fut["px"].to_numpy(dtype=np.float64)
    i_now = np.searchsorted(ts, event_ts, side="right") - 1
    if i_now < 1:
        return {f"futret_{lb}ms": 0.0 for lb in CFG.fut_lookbacks_ms}
    px_now = float(px[i_now])
    if px_now <= 0:
        return {f"futret_{lb}ms": 0.0 for lb in CFG.fut_lookbacks_ms}
    for lb_ms in CFG.fut_lookbacks_ms:
        lb = lb_ms / 1000.0
        i_prev = np.searchsorted(ts, event_ts - lb, side="right") - 1
        if i_prev < 0 or px[i_prev] <= 0:
            out[f"futret_{lb_ms}ms"] = 0.0
            continue
        ret = (px_now - float(px[i_prev])) / float(px[i_prev])
        out[f"futret_{lb_ms}ms"] = float(sign * ret)
    return out


