# SECTION 3c — FEATURE C: DEEP-BOOK QUEUE DEPLETION
# ══════════════════════════════════════════════════════════════════
def feat_queue_depletion(l2: pd.DataFrame, event_ts: float, direction: str) -> Dict[str, float]:
    """
    Direction-adjusted order-book pull/refill in the pre-event window.
    For UP: ask-side withdrawal is supportive. For DOWN: bid-side withdrawal.
    """
    # Use _ts_sec fast path
    if "_ts_sec" in l2.columns:
        t0 = event_ts - CFG.pre_window_sec
        w = l2[(l2["_ts_sec"] >= t0) & (l2["_ts_sec"] <= event_ts)].reset_index(drop=True)
    else:
        # Fallback conversion
        ts_vals = l2[CFG.c_ts].to_numpy(dtype=np.float64) / (1000.0 if CFG.ts_is_ms else 1.0)
        mask = (ts_vals >= event_ts - CFG.pre_window_sec) & (ts_vals <= event_ts)
        w = l2.loc[mask].reset_index(drop=True)
    out = {"deplete_vel": 0.0, "refill_ratio": 1.0, "deep_decay": 0.0, "imbalance": 0.0}
    if len(w) < 3:
        return out
    up = (direction == "UP")
    qcol   = CFG.c_sq1 if up else CFG.c_bq1
    deepcs = CFG.c_sq_deep if up else CFG.c_bq_deep
    if qcol not in w.columns:
        return out
    q  = w[qcol].to_numpy(dtype=float)
    # ts for dt
    if "_ts_sec" in w.columns:
        tq = w["_ts_sec"].to_numpy(dtype=float)
    else:
        tq = w[CFG.c_ts].to_numpy(dtype=float) / (1000.0 if CFG.ts_is_ms else 1.0)
    dq = np.diff(q)
    consumed = float(-np.minimum(dq, 0).sum())
    refilled = float(np.maximum(dq, 0).sum())
    dt = float(max(tq[-1] - tq[0], 1e-6))
    out["deplete_vel"]  = float((consumed - refilled) / dt)
    out["refill_ratio"] = float(refilled / max(consumed, 1e-6))
    # deep level decay: sum of 3-5
    try:
        # Guard missing cols
        present = [c for c in deepcs if c in w.columns]
        if present:
            deep = w[present].sum(axis=1).to_numpy(dtype=float)
            if len(deep) > 1 and deep[0] > 0:
                out["deep_decay"] = float((deep[0] - deep[-1]) / deep[0])
    except Exception:
        pass
    # top-of-book imbalance, direction-adjusted
    try:
        bq = w[CFG.c_bq1].to_numpy(dtype=float); sq = w[CFG.c_sq1].to_numpy(dtype=float)
        den = (bq + sq); den[den == 0] = 1e-9
        imb = (bq - sq) / den
        last = float(imb[-1])
        out["imbalance"] = float(-last) if up else float(last)
    except Exception:
        pass
    return out


