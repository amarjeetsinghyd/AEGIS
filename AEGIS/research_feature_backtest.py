# SECTION 4 — ASSEMBLE FEATURE MATRIX
# ══════════════════════════════════════════════════════════════════
def extract_all(labels: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict] = []
    n = len(labels)
    # Group labels by sym to reduce cache slicing? Simple loop is fine for ~1-2k rows
    for i, r in labels.iterrows():
        t0 = float(r["ts"]) - CFG.pre_window_sec - 0.5
        t1 = float(r["ts"]) + CFG.horizon_sec
        # Cache slice for this sym in extended range, then sub-slice per feature
        l2_full = _read_range(str(r["sym"]), t0, t1)
        fut = load_futures(t0, t1)
        if l2_full.empty:
            # Controls may be on non-trading days or outside cache range — skip gracefully
            continue
        # For event-intensity and queue depletion we want only the pre-window symbol ticks
        # but the loader already filtered to sym — that's correct.
        feats: Dict[str, float] = {}
        # Futures lead-lag can use index proxy; if empty it's zeros
        try:
            feats.update(feat_futures_lead_lag(fut, float(r["ts"]), str(r["dir"])))
        except Exception as e:
            warnings.warn(f"futures feats failed for {r['sym']}@{r['ts']}: {e}")
            feats.update({f"futret_{lb}ms": 0.0 for lb in CFG.fut_lookbacks_ms})
        try:
            feats.update(feat_event_intensity(l2_full, float(r["ts"])))
        except Exception as e:
            warnings.warn(f"intensity failed for {r['sym']}@{r['ts']}: {e}")
            feats.update({"tick_rate": 0.0, "rate_accel": 1.0, "fano": 1.0, "excit": 1.0, "hawkes_n": float("nan")})
        try:
            feats.update(feat_queue_depletion(l2_full, float(r["ts"]), str(r["dir"])))
        except Exception as e:
            warnings.warn(f"queue feats failed for {r['sym']}@{r['ts']}: {e}")
            feats.update({"deplete_vel": 0.0, "refill_ratio": 1.0, "deep_decay": 0.0, "imbalance": 0.0})
        feats.update({"ts": float(r["ts"]), "y": int(r["y"]), "sym": str(r["sym"])})
        rows.append(feats)
        if (i + 1) % 100 == 0 or (i + 1) == n:
            print(f"  extracted {i+1}/{n} (kept {len(rows)})")
    df = pd.DataFrame(rows)
    if not df.empty:
        df = df.sort_values("ts").reset_index(drop=True)
    return df


