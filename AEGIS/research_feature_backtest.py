# SECTION 3b — FEATURE B: EVENT-STREAM INTENSITY
# ══════════════════════════════════════════════════════════════════
def _hawkes_branching_mle(times: np.ndarray, T: float, beta: float) -> float:
    """Rigorous exponential-kernel Hawkes branching ratio n = alpha/beta via MLE."""
    from scipy.optimize import minimize
    if len(times) < 20:
        return float("nan")
    dt = np.diff(times)
    A = np.empty(len(times)); A[0] = 0.0
    for i in range(1, len(times)):
        A[i] = math.exp(-beta * dt[i-1]) * (A[i-1] + 1.0)
    tail = (1.0 - np.exp(-beta * (T - times))) / beta
    def nll(p):
        mu, alpha = p
        lam = mu + alpha * A
        if np.any(lam <= 0):
            return 1e9
        return -np.sum(np.log(lam)) + mu * T + alpha * tail.sum()
    lam_mean = len(times) / max(T, 1e-9)
    res = minimize(nll, x0=np.array([lam_mean * 0.5, beta * 0.3]),
                   bounds=[(1e-6, None), (1e-6, beta * 0.99)], method="L-BFGS-B",
                   options={"maxiter": 200})
    alpha = float(res.x[1])
    return float(min(alpha / beta, 0.99))

def feat_event_intensity(l2: pd.DataFrame, event_ts: float) -> Dict[str, float]:
    """
    Tick-arrival clustering in the pre-event window.
      - tick_rate  : events/sec
      - rate_accel : recent half / earlier half (>1 = accelerating)
      - fano       : Var(count)/Mean(count) over 100ms bins (>1 = clustered)
      - excit      : excess of short gaps vs Poisson
      - hawkes_n   : branching ratio (only if use_hawkes_mle=True)
    """
    t0 = event_ts - CFG.pre_window_sec
    # Use _ts_sec if present (cache), else c_ts conversion
    if "_ts_sec" in l2.columns:
        tcol = "_ts_sec"
    elif CFG.c_ts in l2.columns:
        # Convert ad-hoc
        vals = l2[CFG.c_ts].to_numpy(dtype=np.float64)
        if CFG.ts_is_ms:
            vals = vals / 1000.0
        w_ts = vals  # used below via manual mask
        mask = (w_ts >= t0) & (w_ts <= event_ts)
        # Reconstruct small frame view
        w = l2.loc[mask]
        tcol = None
        t = w_ts[mask]
    else:
        tcol = CFG.c_ts

    if "_ts_sec" in l2.columns:
        w = l2[(l2["_ts_sec"] >= t0) & (l2["_ts_sec"] <= event_ts)]
        t = w["_ts_sec"].to_numpy(dtype=np.float64) if len(w) else np.array([])
    out = {"tick_rate": 0.0, "rate_accel": 1.0, "fano": 1.0, "excit": 1.0, "hawkes_n": float("nan")}
    # Options can be sparse (0.5-2 ticks/sec), so require >=3 not 10
    if len(t) < 3 if 't' in locals() else len(w) < 3:
        return out
    if 't' not in locals():
        t = w[tcol].to_numpy(dtype=np.float64)
        if CFG.ts_is_ms:
            # Should already be _ts_sec path; fallback
            t = t / 1000.0
    T = CFG.pre_window_sec
    out["tick_rate"] = float(len(t) / max(T, 1e-9))
    mid = event_ts - T / 2.0
    early = int(np.sum(t < mid)); late = int(np.sum(t >= mid))
    out["rate_accel"] = float((late + 1e-6) / (early + 1e-6))
    # Fano factor over 100ms bins
    nbins = max(1, int(T / 0.1))
    bins = np.histogram(t, bins=nbins)[0].astype(np.float64)
    if bins.mean() > 0:
        out["fano"] = float(bins.var() / max(bins.mean(), 1e-9))
    # excess short-gap clustering vs Poisson
    if len(t) >= 2:
        it = np.diff(t)
        lam = len(t) / max(T, 1e-9)
        if lam > 0 and len(it):
            p_short = float(np.mean(it < 0.05))
            out["excit"] = float(p_short / max(lam * 0.05, 1e-6))
    if CFG.use_hawkes_mle and len(t) >= 20:
        try:
            out["hawkes_n"] = float(_hawkes_branching_mle(t, T, CFG.hawkes_beta))
        except Exception:
            out["hawkes_n"] = float("nan")
    return out


