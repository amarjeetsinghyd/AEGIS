# SECTION 6 — WALK-FORWARD TRIGGER SIMULATION
# ══════════════════════════════════════════════════════════════════
def walk_forward(df: pd.DataFrame, feat: str, cost_bps: float = 2.0) -> None:
    """
    Simple threshold trigger on the best feature, evaluated OOS.
    Hit = a >=10% spike actually starts within horizon of the trigger.
    """
    df = df.sort_values("ts").reset_index(drop=True)
    split = int(len(df)*0.7)
    test = df.iloc[split:].copy()
    train = df.iloc[:split]
    if test.empty or train.empty:
        print("  walk-forward: no OOS data"); return
    # Drop NaN in feat for threshold scan
    train_valid = train[np.isfinite(train[feat])]
    if train_valid.empty:
        print(f"  walk-forward: feature '{feat}' all NaN in train"); return
    best_thr, best_p = None, -1.0
    for q in np.linspace(0.90, 0.995, 20):
        thr = train_valid[feat].quantile(q)
        sel = train_valid[train_valid[feat] >= thr]
        if len(sel) < 5: continue
        prec = float(sel["y"].mean())
        if prec > best_p:
            best_p, best_thr = prec, float(thr)
    if best_thr is None:
        print("  walk-forward: could not find threshold (too few high quantiles)"); return
    fired = test[test[feat] >= best_thr]
    hits  = float(fired["y"].mean()) if len(fired) else 0.0
    base = float(test["y"].mean()) if len(test) else 0.0
    lift = hits / max(base, 1e-9)
    print(f"\n  Walk-forward on '{feat}':")
    print(f"    threshold={best_thr:.6g}  (train prec @thr = {best_p:.3f})")
    print(f"    triggers_OOS={len(fired)}/{len(test)}  hit_rate={hits:.3f}  base_rate_OOS={base:.3f}")
    print(f"    lift vs base = {lift:.2f}x   (needs to clear costs={cost_bps}bps + slippage to be tradable)")
    if lift < 1.2:
        print("    -> ~random (no edge)")
    elif lift < 2.0:
        print("    -> weak lift")
    else:
        print("    -> strong lift (worth paper-trading)")

