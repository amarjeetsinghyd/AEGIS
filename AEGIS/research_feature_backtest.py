# SECTION 2 — MATCHED CONTROLS  (critical to avoid base-rate bias)
# ══════════════════════════════════════════════════════════════════
def _available_days() -> List[str]:
    """Return sorted YYYY-MM-DD days present in cache."""
    df = _ensure_l2_cache()
    days = pd.to_datetime(df["_ts_sec"], unit="s").dt.strftime("%Y-%m-%d").unique().tolist()
    return sorted(days)

def build_controls(spikes: pd.DataFrame) -> pd.DataFrame:
    """
    Matched controls that preserve symbol validity across weekly expiry rolls.
    Instead of 'same symbol other day' (which fails when expiry rolls),
    sample same symbol OTHER TIME same day, matched on time-of-day jitter
    and guaranteed >min_gap from any spike. This keeps controls in-sample
    for that expiry and ensures the L2 window actually exists.
    Falls back to other-day same strike if same-day is impossible.
    """
    rng = np.random.default_rng(42)
    spike_ts = spikes["ts"].to_numpy(dtype=np.float64)
    df = _ensure_l2_cache()
    # Precompute per-day session bounds in UTC sec
    def _day_bounds_utc(day_str: str) -> Tuple[float, float]:
        # 09:15-15:30 IST = 03:45-10:00 UTC
        d0 = pd.Timestamp(day_str).timestamp()
        return d0 + 3*3600 + 45*60, d0 + 10*3600
    avail_days = _available_days()
    # Build per-sym per-day spike exclusion map for quick check
    rows: List[Dict] = []
    # For each spike, generate controls on SAME day first
    for _, r in spikes.iterrows():
        sym = str(r["sym"])
        ts = float(r["ts"])
        day_str = pd.to_datetime(ts, unit="s").strftime("%Y-%m-%d")
        lo, hi = _day_bounds_utc(day_str)
        # Spike time-of-day for jitter
        tod = ts % 86400.0
        attempts = 0
        found = 0
        need = CFG.control_per_case
        # Same-day TOD-matched controls (±15 min jitter) — preserves intraday regime
        while found < need and attempts < need * 120:
            attempts += 1
            cand = (pd.Timestamp(day_str).timestamp() + tod + rng.uniform(-900, 900))  # ±15 min TOD jitter
            if cand < lo or cand > hi:
                continue
            if spike_ts.size and np.min(np.abs(spike_ts - cand)) < CFG.min_gap_sec:
                continue
            # Ensure this sym actually has ticks near cand (check cache quickly)
            # Quick existence: count ticks for sym within ±5 min of cand
            # Use vectorized check on cache? For speed just trust and let extract filter empty later,
            # but we can pre-filter using per-sym day presence
            # Check if sym exists that day at all
            if sym not in df[df["_ts_sec"].between(lo, hi)][df.columns[0]].values:
                # Light check: see if any tick for sym that day exists in cache (approx)
                # If not, skip — try other day fallback below
                pass
            rows.append({"ts": cand, "sym": sym, "dir": r["dir"], "y": 0})
            found += 1
        # If still short, fallback to other-day same strike/side (expiry-aware)
        if found < need:
            # Extract strike/side from sym to match on other days' active contract
            try:
                # sym format NIFTY18AUG26C24150 -> strike is last 5 digits, side is C/P before it
                import re
                m = re.search(r'([CP])(\d{4,5})$', sym)
                strike = m.group(2) if m else None
                side_c = m.group(1) if m else None
            except Exception:
                strike = None; side_c = None
            other_days = [d for d in avail_days if d != day_str]
            for od in other_days:
                if found >= need:
                    break
                # Find any sym on other day with same strike and side
                od_lo, od_hi = _day_bounds_utc(od)
                day_syms = df[(df["_ts_sec"] >= od_lo) & (df["_ts_sec"] <= od_hi)]["sym"].unique().tolist() if "sym" in df.columns else []
                # Filter to matching strike/side
                cand_syms = [s for s in day_syms if strike and strike in s and (f'{side_c}{strike}' in s)] if strike else []
                if not cand_syms:
                    # fallback to any option on that day
                    cand_syms = [s for s in day_syms if s != "NIFTY"][:3]
                for cs in cand_syms[:1]:
                    cand = pd.Timestamp(od).timestamp() + tod + rng.uniform(-300, 300)
                    if spike_ts.size and np.min(np.abs(spike_ts - cand)) < CFG.min_gap_sec:
                        continue
                    rows.append({"ts": cand, "sym": cs, "dir": r["dir"], "y": 0})
                    found += 1
                    if found >= need:
                        break
    ctrl = pd.DataFrame(rows)
    if ctrl.empty:
        return ctrl
    ctrl = ctrl.sample(frac=1.0, random_state=42).reset_index(drop=True)
    want = len(spikes) * CFG.control_per_case
    return ctrl.head(want)

def label_frame(spikes: pd.DataFrame) -> pd.DataFrame:
    pos = spikes.copy(); pos["y"] = 1
    neg = build_controls(spikes)
    if neg.empty:
        warnings.warn("No controls generated — using positives only (AUC will be 0.5)")
        return pos.sort_values("ts").reset_index(drop=True)
    return pd.concat([pos, neg], ignore_index=True).sort_values("ts").reset_index(drop=True)


