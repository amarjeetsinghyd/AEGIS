def wire_engine_to_executor(engine, executor):
    """Monkey-patch Engine to push Real-Time Metrics & Bucket Aggregates to Executor.
    Handles both dict-based on_tick and zero-copy on_tick_parsed paths."""
    original_on_tick = engine.on_tick
    original_on_tick_parsed = engine.on_tick_parsed
    original_process_bucket = engine._process_bucket

    def wrapped_on_tick(msg):
        original_on_tick(msg)
        try:
            tok = str(msg.get("token", ""))
            sym = engine.t2s.get(tok)
            if sym and sym in engine.last_snap:
                adv = engine.last_snap[sym].get("_adv")
                if adv:
                    executor.update_adv_metrics(sym, adv)
        except Exception:
            pass  # Silent fail on metrics push

    def wrapped_on_tick_parsed(tick):
        original_on_tick_parsed(tick)
        try:
            sym = engine.t2s.get(tick.tok)
            if sym and sym in engine.last_snap:
                adv = engine.last_snap[sym].get("_adv")
                if adv:
                    executor.update_adv_metrics(sym, adv)
        except Exception:
            pass

    def wrapped_process_bucket(sym: str, lp: float, nows: float, dt: float):
        original_process_bucket(sym, lp, nows, dt)
        try:
            if sym not in engine.last_snap: return
            st = engine.last_snap[sym]
            adv = st.get("_adv", {})
            
            tv = engine.cur_tot_val.get(sym, 0.0)
            tc = max(1, engine.cur_tick_count.get(sym, 1))
            whale_conc = engine.cur_max_tick_val.get(sym, 0.0) / max(tv, 1.0)
            whale_z = engine._calculate_whale_z(sym, whale_conc)
            net_vac = engine.cur_net_vacuum.get(sym, 0.0)
            
            # Branching calculated inside _process_bucket, stored in adv temporarily
            branching = adv.get("branching", 1.0)
            
            tox_hist = list(engine.toxicity_history.get(sym, []))
            
            # Compute dkla_toxicity from available engine state (same formula as in _process_bucket)
            # tpin = (buy_val - sell_val) / bucket_cap
            bucket_cap = engine.bucket_map.get(sym, engine.CFG["bucket_turnover"])
            buy_val = engine.cur_buy_val.get(sym, 0.0)
            sell_val = engine.cur_sell_val.get(sym, 0.0)
            tpin = (buy_val - sell_val) / max(bucket_cap, 1.0)
            eff_lam = adv.get("eff_lam", 0.0)
            dkla_tox = eff_lam * abs(tpin)
            
            bucket_aggs = {
                "net_vacuum_bps": net_vac,
                "branching": branching,
                "whale_z": whale_z,
                "toxicity_history": tox_hist,
                "dkla_toxicity": dkla_tox,
            }
            executor.update_bucket_aggregates(sym, bucket_aggs)
        except Exception:
            pass

    engine.on_tick = wrapped_on_tick
    engine.on_tick_parsed = wrapped_on_tick_parsed
    engine._process_bucket = wrapped_process_bucket
    logger.info("[WIRING] Engine -> Executor Metrics Feed Active (Adv + Bucket Aggregates) [Zero-Copy Compatible]")

