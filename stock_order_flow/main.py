    # ─── TIER 2 INTRADAY FILTER (15-min rolling) ───
    def _run_intraday_tier2(self):
        """Run every 15 min: score active symbols, select top 30/15."""
        # Collect stats for all symbols currently in compiler
        all_stats = {}
        for sym in self.compiler.token_to_symbol.values():
            st = self.compiler.get_15min_stats(sym)
            if not st or st['ticks_per_min'] < 3:  # minimum activity
                continue
            all_stats[sym] = st
        
        if len(all_stats) < 10:
            return  # not enough data yet
        
        # Percentile normalization across all symbols
        def pctile(vals, x):
            return sum(1 for v in vals if v <= x) / len(vals)
        
        ticks = [s['ticks_per_min'] for s in all_stats.values()]
        vols  = [s['vol_per_min'] for s in all_stats.values()]
        sprds = [s['avg_spread_bps'] for s in all_stats.values()]
        trades = [s['trade_value_per_min'] for s in all_stats.values()]
        mvols = [s['microprice_vol'] for s in all_stats.values()]
        
        scores = {}
        bias_map = {}
        for sym, s in all_stats.items():
            scores[sym] = (
                0.25 * pctile(ticks, s['ticks_per_min']) +
                0.20 * pctile(vols, s['vol_per_min']) +
                0.20 * (1 - pctile(sprds, s['avg_spread_bps'])) +  # tight = good
                0.20 * pctile(trades, s['trade_value_per_min']) +
                0.10 * (1 - pctile(mvols, s['microprice_vol'])) +  # stable = good
                0.05 * abs(s['oib'])
            )
            # Multi-Parameter 15-Minute Macro Directional Trend Bias
            ret_15m = s.get('ret_15m', 0.0)
            vwap_dist = s.get('vwap_dist', 0.0)
            oib = s.get('oib', 0.0)
            
            # Composite Directional Score: Price Return (45%) + VWAP Distance (35%) + Order Imbalance (20%)
            dir_score = 0.45 * (ret_15m / 0.15) + 0.35 * (vwap_dist / 0.10) + 0.20 * (oib / 0.20)
            
            if dir_score >= 1.0 and ret_15m > 0 and vwap_dist >= 0:
                bias_map[sym] = "LONG_ONLY"
            elif dir_score <= -1.0 and ret_15m < 0 and vwap_dist <= 0:
                bias_map[sym] = "SHORT_ONLY"
            else:
                bias_map[sym] = "NO_TRADE"  # Pure flat noise or conflicting signals - reject
        
        ranked = sorted(scores, key=scores.get, reverse=True)
        top30 = ranked[:30]
        # Prioritize symbols with clear directional momentum (LONG_ONLY / SHORT_ONLY)
        directional_top = [sym for sym in top30 if bias_map.get(sym) in ("LONG_ONLY", "SHORT_ONLY")]
        top15 = directional_top[:15] if directional_top else top30[:15]
        
        # Push to compiler + engine
        self.compiler.set_tier2_symbols(top30)
        self.compiler.set_engine_symbols(top15)
        if hasattr(self.engine, "set_symbol_bias_map"):
            self.engine.set_symbol_bias_map(bias_map)
        
        # Reset 15-min stats for next window
        self.compiler.reset_15min_stats()
        
        n_long = sum(1 for b in bias_map.values() if b == 'LONG_ONLY')
        n_short = sum(1 for b in bias_map.values() if b == 'SHORT_ONLY')
        n_flat = sum(1 for b in bias_map.values() if b == 'NO_TRADE')
        logger.info(f"[TIER2] {datetime.now().strftime('%H:%M')} | "
                    f"Top15: {top15} | Macro Bias Summary: LONG={n_long}, SHORT={n_short}, FLAT(NO_TRADE)={n_flat}")

    def run(self):
        """Main Event Loop: Heartbeat, Price Updates, Signal Processing."""
        last_heartbeat_min = -1
        logger.info("ENTERING MAIN LOOP. System Live.")
        
        while not self.shutdown_event.is_set():
            try:
                now = datetime.now()
                
                # --- HEARTBEAT & LOGGING (1 Min) ---
                if now.minute != last_heartbeat_min:
                    last_heartbeat_min = now.minute
                    if is_trading_day(now.date()) and is_market_open(now) and not is_pre_market(now):
                        summary = self.engine.get_market_state_summary()
                        pos_summary = self.executor.get_open_positions_summary()
                        logger.info(f"[HB] {now.strftime('%H:%M')} | {summary}")
                        if pos_summary != "No open positions":
                            logger.info(f"[POS]\n{pos_summary}")
                        
                        # ULTRA-DETAILED TELEMETRY: Gate status summary for active symbols
                        active_symbols = [s for s in self.engine.cur_tot_val if self.engine.cur_tot_val[s] > 0]
                        if active_symbols:
                            gate_status = []
                            for sym in active_symbols[:5]:  # Limit to top 5 to avoid log spam
                                st = self.engine.last_snap.get(sym, {})
                                adv = st.get("_adv", {})
                                tc = self.engine.cur_tick_count.get(sym, 0)
                                tv = self.engine.cur_tot_val.get(sym, 0)
                                target_bucket = self.engine.bucket_map.get(sym, self.engine.CFG["bucket_turnover"])
                                pct = (tv / target_bucket) * 100
                                
                                # Quick gate check
                                gate_ticks = tc >= self.engine.TRIG["min_ticks"]
                                gate_status.append(f"{sym}:{pct:.0f}% T:{tc} {'✅' if gate_ticks else '❌'}")
                            
                            logger.info(f"[GATE_STATUS] Active Buckets: {' | '.join(gate_status)}")

                        # --- TIER 2 INTRADAY FILTER (Every 15 min: :00, :15, :30, :45) ---
                        if now.minute % 15 == 0 and now.second < 10:
                            if not hasattr(self, '_last_tier2_min') or self._last_tier2_min != now.minute:
                                self._last_tier2_min = now.minute
                                self._run_intraday_tier2()

                # --- TIME GATES ---
                if not is_bot_active_hours(now):
                    logger.info("Active Hours Closed. Sleeping until Pre-Market...")
                    sleep_until_next_premarket()
                    # Re-login & Resubscribe on Wake
                    if hasattr(self.broker, "session_provider"):
                        self.broker.session_provider._restore_or_login()
                    self.compiler.subscribe(list(self.master_token_map.keys()))
                    last_heartbeat_min = -1 # Force HB log
                    continue
                    
                if is_pre_market(now):
                    time.sleep(1)
                    continue

                if not is_trading_day(now.date()) or now.time() > MARKET_CLOSE_TIME:
                    time.sleep(60)
                    continue

                # --- PRICE UPDATE (Executor Needs Fresh Prices for Exits) ---
                current_prices = {}
                # Use compiler's market_depth (updated by WebSocket thread)
                for tok, sym in self.compiler.token_to_symbol.items():
                    # Only update prices for Active Universe to save cycles
                    if sym in self.engine.t2s.values():
                        depth = self.compiler.market_depth.get(tok)
                        if depth and depth.get("lp", 0) > 0:
                            # Freshness Check (3 sec)
                            if time.time() - depth.get("ts", 0) < 3.0:
                                current_prices[sym] = depth["lp"]
                
                if current_prices:
                    self.executor.update_prices(current_prices)

                # --- SIGNAL PROCESSING (Entry Gateway) ---
                if not self.engine.signal_queue.empty():
                    signal_data = self.engine.signal_queue.get()
                    
                    # Global Mutex: Max 1 Position (Configurable in Executor)
                    if len(self.executor.open_trades) >= self.executor.max_open_positions:
                        logger.info(f"[GATE] Max Positions Reached. Ignoring Signal: {signal_data}")
                        continue
                    
                    # Worker Health Check
                    if not self.executor.worker_thread.is_alive():
                        logger.critical("Executor Worker Thread DEAD. Halting Entries.")
                        time.sleep(5)
                        continue
                    
                    # Entry Time Cutoff (14:45)
                    if now.time() >= dt_time(14, 45):
                        logger.info("[GATE] Entry Cutoff (14:45) Passed. Ignoring Signal.")
                        continue

                    best_sym = signal_data["sym"]
                    signal = signal_data["signal"]
                    reason = signal_data["reason"]
                    lp = signal_data["lp"]
                    metrics = signal_data.get("metrics", {})
                    macro_tag = self.universe.get(best_sym, {}).get("macro_tag", "TWO_WAY")
                    
                    logger.info(f"🚀 SIGNAL: {best_sym} [{macro_tag}] -> {signal} | {reason} @ {lp:.2f} | Conv: {signal_data.get('conviction', 0):.1f}")
                    
                    # ULTRA-DETAILED TELEMETRY: Log entry decision with full conviction metrics from signal
                    if metrics:
                        logger.info(
                            f"[ENTRY_DECISION_MAIN] {best_sym} | Side: {signal} | LP: {lp:.2f} | "
                            f"Conviction: {signal_data.get('conviction', 0):.2f} | "
                            f"TPIN: {metrics.get('tpin', 0):.5f} | Branching: {metrics.get('branching', 0):.3f} | "
                            f"WhaleZ: {metrics.get('whale_z', 0):.2f} | Toxicity: {metrics.get('dkla_toxicity', 0):.1f} | "
                            f"NetVac: {metrics.get('net_vacuum_bps', 0):.1f}bps | "
                            f"MPAR: {metrics.get('mpar_score', 0):.3f} | LRA: {metrics.get('lra_signal', 0):.3f} | "
                            f"DKLA: {metrics.get('dkla_asymmetry', 0):.3f} | MicroDev: {metrics.get('micro_dev', 0):.6f}"
                        )
                    
                    self.executor.enqueue_entry(signal, best_sym, lp, reason, metrics=metrics)

                # Loop Yield (50ms = 20Hz Polling)
                time.sleep(0.05)

            except Exception as e:
                logger.error(f"Main Loop Error: {e}", exc_info=True)
                time.sleep(1.0)

        self.shutdown()

