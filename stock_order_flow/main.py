def calibrate_buckets(broker, token_map: Dict[str, str], universe: Dict) -> tuple[Dict, Dict]:
    """Fetch 3M Daily History -> Calc Median Turnover -> Set Bucket (2x) & Vacuum (0.125x Bucket).
    Only fetches for ACTIVE UNIVERSE symbols to save API calls and time."""
    from stock_order_flow.historical_data_manager import fetch_and_seed_history
    
    # Only calibrate for Active Trading Universe tokens
    # token_map is {token: symbol} — invert against the universe symbol set.
    universe_tokens = {tok: sym for tok, sym in token_map.items() if sym in universe}
    tokens = list(universe_tokens.keys())
    logger.info(f"Fetching history for {len(tokens)} universe tokens (Calibration)...")
    hist_data = fetch_and_seed_history(broker, tokens, universe_tokens)
    
    bucket_map = {}
    vacuum_map = {}
    
    for token_str, df in hist_data.items():
        sym = universe_tokens.get(str(token_str), str(token_str))
            
        if df is not None and not df.empty and len(df) > 20:
            median_vol = df['volume'].median()
            last_close = df['close'].iloc[-1]
            avg_daily_turnover = median_vol * last_close
            
            # Bucket = 2x Avg Daily Turnover (Target ~2 Cr min, scales with liquidity)
            b_val = max(2_00_00_000.0, avg_daily_turnover * 2.0)
            # Vacuum Threshold = 12.5% of Bucket (2.5 Cr default for 2 Cr bucket)
            v_val = max(2_50_00_000.0, b_val * 0.125)
            
            bucket_map[sym] = b_val
            vacuum_map[sym] = v_val
            logger.info(f"[CALIB] {sym:12s} | AvgTO: {avg_daily_turnover/1e7:6.1f}Cr | Bucket: {b_val/1e7:5.1f}Cr | Vac: {v_val/1e7:5.1f}Cr")
        else:
            # Fallback defaults
            bucket_map[sym] = 2_00_00_000.0
            vacuum_map[sym] = 2_50_00_000.0
            
    return bucket_map, vacuum_map

