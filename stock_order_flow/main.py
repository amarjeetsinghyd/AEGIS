def load_universe() -> Dict:
    """Load universe.json generated by Scanner (16:05 previous day)."""
    try:
        if os.path.exists(UNIVERSE_PATH):
            with open(UNIVERSE_PATH, "r") as f:
                data = json.load(f)
            stocks = data.get("stocks", [])
            if stocks:
                uni = {}
                for s in stocks:
                    uni[s["symbol"]] = {
                        "token": str(s["token"]),
                        "search": s.get("search", []),
                        "macro_tag": s.get("macro_tag", "TWO_WAY"),
                        "conviction": s.get("conviction", 0.0)
                    }
                logger.info(f"Universe loaded: {len(uni)} stocks (Date: {data.get('date')})")
                return uni
    except Exception as e:
        logger.warning(f"universe.json read failed ({e}) — CHECK SCANNER OUTPUT")
    return {}

def build_tsym_map(universe: Dict) -> Dict[str, str]:
    """Map Symbol -> TSYM for Execution Manager (Shoonya Order Format)."""
    m = {}
    for sym, meta in universe.items():
        search = meta.get("search", [])
        if isinstance(search, list) and search:
            m[sym] = str(search[0])
        elif isinstance(search, str) and search:
            m[sym] = search
        else:
            m[sym] = f"{sym}-EQ"
    return m

def get_master_token_map(universe: Dict, archiver_tokens: Set[str]) -> Dict[str, str]:
    """
    Combine Value Engine Universe Tokens + Archiver Hardcoded Tokens.
    Returns {token: symbol} for WebSocket Subscription & TickCompiler.
    """
    token_map = {}
    # 1. Active Trading Universe (Value Engine)
    for sym, meta in universe.items():
        token_map[meta["token"]] = sym
    
    # 2. Archiver Extra Tokens (Passive Logging Only)
    # Note: Archiver internally filters its 110 list, but we must subscribe to them here.
    # We need reverse lookup for tokens not in universe. 
    # Since Archiver has its own hardcoded symbol list, we rely on the global token cache.
    try:
        if os.path.exists(TOKEN_CACHE_PATH):
            with open(TOKEN_CACHE_PATH, "r") as f:
                cache = json.load(f)
            for sym in archiver_tokens:
                if sym in cache and "token" in cache[sym]:
                    tok = str(cache[sym]["token"])
                    if tok not in token_map:
                        token_map[tok] = sym # Archiver symbols map to themselves
    except Exception as e:
        logger.warning(f"Token cache merge failed: {e}")
        
    return token_map

