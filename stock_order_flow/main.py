        logger.info("Waiting for Executor Thread to settle...")
        time.sleep(2.0)
        
        # 3. Flush Archiver (CRITICAL: Save Final Partition)
        if self.archiver:
            logger.info("Flushing L2 Archiver Final Partition...")
            self.archiver.shutdown() # Blocking flush
            logger.info("Archiver Flush Complete.")
            
        # 4. Save Executor State
        self.executor._save_open()
        logger.info("Executor State Saved.")
        
        logger.info("SHUTDOWN COMPLETE. Safe to Terminate.")

